import { test, expect, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
const en = JSON.parse(readFileSync(new URL('../../src/core/locales/en.json', import.meta.url), 'utf8')) as Record<string, string>;
const password = 'Integration-Only-Password-37!';
async function login(page: Page, email = 'admin@example.test') {
  await page.goto('/auth');
  await page.locator('input[type=email]').fill(email);
  await page.locator('input[type=password]').fill(password);
  await page.locator('button[type=submit]').click();
  await expect(page).toHaveURL(/dashboard/);
}

test('staff can register, edit, schedule, reschedule, invoice and record payments', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('hms_lang', 'en'));
  await login(page);
  await page.reload();
  await expect(page.getByText('Clinical Performance & Analytics')).toBeVisible();

  await page.goto('/patients');
  await page.getByRole('button', { name: en.registerPatient, exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel(en.fullName).fill('Browser Patient');
  await dialog.getByLabel('Date of Birth').fill('1990-04-10');
  await dialog.getByLabel(en.contactPhone).fill('0551234567');
  await dialog.getByLabel(en.colEmailAddress).fill('browser-patient@example.test');
  await dialog.getByLabel(en.genderIdentity).selectOption('Other');
  await dialog.getByRole('button', { name: en.saveRecord }).click();
  await expect(dialog).toBeHidden();
  let patientRow = page.getByRole('row').filter({ hasText: 'Browser Patient' });
  await expect(patientRow).toBeVisible();
  await patientRow.getByRole('button', { name: 'Edit patient' }).click();
  await expect(dialog.getByLabel(en.fullName)).toHaveValue('Browser Patient');
  await dialog.getByLabel(en.fullName).fill('Browser Patient Updated');
  await dialog.getByRole('button', { name: en.applyChanges }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('row').filter({ hasText: 'Browser Patient Updated' })).toBeVisible();

  await page.goto('/doctors');
  await page.getByRole('button', { name: new RegExp(en.departmentsMasterTab) }).click();
  await page.getByRole('button', { name: en.addDepartment, exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel(en.departmentName).fill('Browser Cardiology');
  await dialog.getByRole('button', { name: en.createDepartment, exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('row').filter({ hasText: 'Browser Cardiology' })).toBeVisible();
  await page.getByRole('button', { name: new RegExp(en.physiciansDirectoryTab) }).click();
  await page.getByRole('button', { name: en.addPhysician, exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('[name=name]').fill('Browser Doctor');
  await dialog.locator('[name=email]').fill('browser-doctor@example.test');
  await dialog.locator('[name=contactNumber]').fill('0551234568');
  await dialog.locator('[name=specialty]').fill('Cardiology');
  await dialog.locator('[name=departmentId]').selectOption({ label: 'Browser Cardiology' });
  await dialog.locator('button').last().click();
  await expect(dialog).toBeHidden();
  await expect(page.getByText('Browser Doctor', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: new RegExp(en.departmentsMasterTab) }).click();
  await page.getByRole('row').filter({ hasText: 'Browser Cardiology' }).getByRole('button', { name: 'Edit department' }).click();
  await page.getByRole('dialog').locator('[name=headOfDepartment]').selectOption({ label: 'Browser Doctor' });
  await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.getByRole('row').filter({ hasText: 'Browser Cardiology' })).toContainText('Browser Doctor');

  await page.goto('/appointments');
  await page.getByRole('button', { name: en.bookAppointment, exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('[name=patientId]').selectOption({ index: 1 });
  await dialog.locator('[name=doctorId]').selectOption({ index: 1 });
  const day = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10);
  await dialog.locator('[name=appointmentDate]').fill(day);
  await dialog.locator('[name=appointmentTime]').fill('10:00');
  await dialog.getByRole('button', { name: en.bookAppointment, exact: true }).click();
  await expect(dialog).toBeHidden();
  const appointmentRow = page.getByRole('row').filter({ hasText: 'Browser Patient Updated' });
  await expect(appointmentRow).toBeVisible();
  await appointmentRow.getByRole('button', { name: en.reschedule, exact: true }).click();
  await page.getByRole('dialog').locator('[name=appointmentTime]').fill('11:00');
  await page.getByRole('dialog').getByRole('button', { name: en.applyReschedule, exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(appointmentRow).toContainText(en.commonRescheduled);

  await page.goto('/billing');
  await page.getByRole('button', { name: en.generateBill, exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('[name=patientId]').selectOption({ index: 1 });
  await dialog.getByRole('button', { name: en.generateAndDispatchInvoice, exact: true }).click();
  await expect(dialog).toBeHidden();
  const billRow = page.getByRole('row').filter({ hasText: 'Browser Patient Updated' });
  await billRow.getByRole('button', { name: en.payBtn, exact: true }).click();
  await page.getByRole('dialog').locator('[name=amountToPay]').fill('50');
  await page.getByRole('dialog').getByRole('button', { name: en.applyPaymentBtn, exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(billRow).toContainText('$50.00');
  await expect(billRow).toContainText('$107.50');
  await billRow.getByTitle('Send Reminder Notification').click();
  await expect(page.getByText(en.toastBillingReminderSent, { exact: true })).toBeVisible();
  await page.goto('/notifications');
  await expect(page.getByRole('row').filter({ hasText: 'Browser Patient Updated' })).toContainText('Pending');
  await page.goto('/dashboard');
  await page.screenshot({ path: info.outputPath('dashboard.png'), fullPage: true });
  await expect(page.getByText('$50.00').first()).toBeVisible();
  expect(errors).toEqual([]);
});

test('staff account creation, clinical editing and Arabic mobile navigation work', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('hms_lang', 'en'));
  await login(page);
  const patientResponse = await page.request.post('/api/patients', { data: { name: 'Clinical Patient', email: 'clinical-patient@example.test', dateOfBirth: '1986-02-03', gender: 'Female', contactNumber: '0551234569', address: '', medicalHistory: '', status: 'Active' } });
  expect(patientResponse.status()).toBe(201);
  await page.goto('/users');
  await page.getByRole('button', { name: en.addStaffAccount, exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.locator('[name=name]').fill('Browser Nurse');
  await dialog.locator('[name=email]').fill('browser-nurse@example.test');
  await dialog.locator('[name=password]').fill(password);
  await dialog.locator('button').last().click();
  await expect(dialog).toBeHidden();
  let row = page.getByRole('row').filter({ hasText: 'browser-nurse@example.test' });
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: 'Edit account' }).click();
  await page.getByRole('dialog').locator('[name=name]').fill('Browser Nurse Updated');
  await page.getByRole('dialog').getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(row).toContainText('Browser Nurse Updated');
  await page.getByTitle(en.logout, { exact: true }).click();
  await expect(page).toHaveURL(/auth/);
  await login(page, 'browser-nurse@example.test');
  await page.goto('/records');
  await page.getByRole('button', { name: en.newClinicalFile, exact: true }).click();
  dialog = page.getByRole('dialog');
  const patients = dialog.locator('[name=patientId]');
  const option = patients.locator('option').filter({ hasText: 'Clinical Patient' });
  await patients.selectOption((await option.getAttribute('value'))!);
  await dialog.locator('[name=diagnosis]').fill('Browser initial diagnosis');
  await dialog.locator('[name=treatment]').fill('Browser treatment plan');
  await dialog.locator('[name=prescriptions]').fill('None');
  await dialog.locator('button').last().click();
  await expect(dialog).toBeHidden();
  await expect(page.getByText('Browser initial diagnosis', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: en.modifyRecordBtn, exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('[name=diagnosis]').fill('Browser revised diagnosis');
  await dialog.locator('button').last().click();
  await expect(dialog).toBeHidden();
  await expect(page.getByText('Browser revised diagnosis', { exact: true })).toBeVisible();
  expect((await page.request.get('/api/billing')).status()).toBe(403);
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath('clinical-arabic-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
